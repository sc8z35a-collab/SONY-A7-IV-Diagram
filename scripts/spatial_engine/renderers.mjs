import fs from 'node:fs';
import path from 'node:path';

export function renderSpatialSliceText(slice, ascii = false) {
  const { name, origin, group, xMin, xMax, yMin, yMax, zMin, zMax, res, nx, nz, stepX, stepZ, sdfMode, freePct, grid, sdfGrid } = slice;
  const maxCols = 64;
  const colStride = Math.max(1, Math.ceil(nx / maxCols));
  const outCols = Math.ceil(nx / colStride);
  const frameTag = group ? `LOCAL@${group}(${origin.join(',')})` : `WORLD(${origin.join(',')})`;

  const lines = [];
  lines.push(
    `\n=== SPATIAL MAP: ${name} | ${frameTag} | Y[${yMin >= 0 ? '+' : ''}${yMin.toFixed(1)}..${yMax >= 0 ? '+' : ''}${yMax.toFixed(1)}] mm | res=${res}mm (${sdfMode ? 'EXACT-SDF' : 'TRI-SAT'}) | free=${freePct}% ===`
  );

  // X ruler
  let xHdr = '    Z\\X | ';
  for (let c = 0; c < outCols; c += 8) {
    const xv = xMin + (c * colStride + colStride * 0.5) * stepX;
    const lbl = `${xv >= 0 ? '+' : ''}${xv.toFixed(1)}`;
    xHdr += lbl.padEnd(8, ' ');
  }
  lines.push(xHdr);
  lines.push('--------+'.padEnd(9 + outCols, '-'));

  for (let iz = 0; iz < nz; iz++) {
    const zv = zMin + (iz + 0.5) * stepZ;
    let rowStr = `${(zv >= 0 ? '+' : '') + zv.toFixed(2)}`.padStart(7, ' ') + ' | ';
    for (let c = 0; c < outCols; c++) {
      const i0 = c * colStride;
      const i1 = Math.min(nx, i0 + colStride);
      if (sdfMode && sdfGrid) {
        let minSdf = Infinity;
        for (let ix = i0; ix < i1; ix++) {
          if (sdfGrid[iz][ix] < minSdf) minSdf = sdfGrid[iz][ix];
        }
        if (minSdf <= 0) rowStr += '#';
        else if (minSdf < 0.2) rowStr += '!';
        else if (minSdf < 0.5) rowStr += ':';
        else if (minSdf < 1.0) rowStr += ascii ? '.' : '·';
        else rowStr += ' ';
      } else {
        // Conservative downsampling: worst occupancy wins
        let val = 0;
        for (let ix = i0; ix < i1; ix++) {
          const v = grid[iz][ix];
          if (v === -2) { val = -2; break; }
          if (v === -1 && val >= 0) val = -1;
          else if (v > val && val >= 0) val = v;
        }
        if (val === -2) rowStr += ascii ? 'X' : '✕';
        else if (val === -1) rowStr += ascii ? '*' : '★';
        else if (val === 0) rowStr += '.';
        else if (val === 1) rowStr += ascii ? '1' : '░';
        else if (val === 2) rowStr += ascii ? '2' : '▒';
        else rowStr += ascii ? '#' : '▓';
      }
    }
    lines.push(rowStr);
  }
  lines.push(
    sdfMode
      ? 'LEGEND (EXACT-SDF mm): #=SOLID(<=0) !=<0.2mm :=<0.5mm ·=<1.0mm (space)=>=1.0mm'
      : 'LEGEND (TRI-SAT): .=FREE ░=1-part ▒=2-parts ▓=3+dense ★=candidate ✕=COLLISION'
  );
  return lines.join('\n');
}

export function emitThreeSnippet(pockets) {
  const lines = ['// Auto-generated by sp (0.001 mm certified free-pocket coordinates)'];
  pockets.forEach((p, idx) => {
    lines.push(
      `const mesh${idx + 1} = new THREE.Mesh(new THREE.BoxGeometry(${p.size[0]}, ${p.size[1]}, ${p.size[2]}), mats.stainlessMachined);`
    );
    lines.push(
      `mesh${idx + 1}.position.set(${p.posLocal[0]}, ${p.posLocal[1]}, ${p.posLocal[2]}); // minGap=${p.minGapMm}mm nearest=${p.nearestPart || 'none'}`
    );
  });
  return lines.join('\n');
}

export function writeSpatialHtmlViewer(unitId, slices, outPath) {
  const abs = path.resolve(outPath);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  const payload = slices.map((s) => ({
    name: s.name,
    xMin: s.xMin, xMax: s.xMax, yMin: s.yMin, yMax: s.yMax, zMin: s.zMin, zMax: s.zMax,
    nx: s.nx, nz: s.nz, freePct: s.freePct, res: s.res,
    grid: s.grid.map((r) => Array.from(r)),
  }));
  const html = `<!doctype html>
<html lang="ja"><head><meta charset="utf-8"><title>sp Spatial Map — ${unitId}</title>
<style>body{margin:0;background:#0b1120;color:#e2e8f0;font-family:system-ui,sans-serif;padding:20px}
.bar{display:flex;gap:12px;align-items:center;margin-bottom:14px}select{background:#1e293b;color:#fff;border:1px solid #334155;padding:6px 10px;border-radius:6px}
canvas{background:#020617;border:1px solid #334155;border-radius:8px;max-width:100%}#info{font-family:monospace;font-size:13px;color:#94a3b8;margin-top:8px}</style></head>
<body><h2>sp 0.001mm Spatial Map — <code>${unitId}</code></h2>
<div class="bar"><label>Slice: <select id="sel"></select></label><span id="meta"></span></div>
<canvas id="cv" width="900" height="520"></canvas><div id="info">Hover canvas for exact (X, Z) coordinates</div>
<script>
const SLICES=${JSON.stringify(payload)};
const sel=document.getElementById('sel'),cv=document.getElementById('cv'),ctx=cv.getContext('2d'),meta=document.getElementById('meta'),info=document.getElementById('info');
SLICES.forEach((s,i)=>{const o=document.createElement('option');o.value=i;o.textContent=s.name+' Y['+s.yMin.toFixed(1)+'..'+s.yMax.toFixed(1)+'] free='+s.freePct+'%';sel.appendChild(o);});
const COLORS={'-2':'#ef4444','-1':'#22c55e','0':'#0f172a','1':'#334155','2':'#64748b','3':'#94a3b8'};
function draw(){const s=SLICES[sel.value];meta.textContent='res='+s.res+'mm | free='+s.freePct+'% | '+s.nx+'x'+s.nz;
const cw=cv.width/s.nx,ch=cv.height/s.nz;ctx.clearRect(0,0,cv.width,cv.height);
for(let iz=0;iz<s.nz;iz++)for(let ix=0;ix<s.nx;ix++){ctx.fillStyle=COLORS[s.grid[iz][ix]]||'#0f172a';ctx.fillRect(ix*cw,iz*ch,Math.ceil(cw),Math.ceil(ch));}}
cv.onmousemove=(e)=>{const s=SLICES[sel.value],r=cv.getBoundingClientRect();const x=s.xMin+(e.clientX-r.left)/r.width*(s.xMax-s.xMin);const z=s.zMin+(e.clientY-r.top)/r.height*(s.zMax-s.zMin);info.textContent='X='+x.toFixed(2)+'mm  Z='+z.toFixed(2)+'mm  Y=['+s.yMin.toFixed(1)+'..'+s.yMax.toFixed(1)+']mm';};
sel.onchange=draw;draw();
</script></body></html>`;
  fs.writeFileSync(abs, html, 'utf8');
  return abs;
}
