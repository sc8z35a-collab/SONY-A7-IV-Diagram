// Build deterministic ordered array of all 530 fixed test definitions (T001..T530)
export const TEST_REGISTRY = (() => {
  const list = [];
  let seq = 1;
  for (const eng of ENGINES) {
    const specs = ENGINE_TEST_SPECS[eng.id] || [];
    for (const [sev, cat, desc] of specs) {
      const id = `T${String(seq).padStart(3, '0')}`;
      list.push(Object.freeze({
        id,
        seq,
        engine: eng.id,
        pillar: eng.pillar,
        sev,
        cat,
        desc,
        solvers: eng.solvers,
      }));
      seq++;
    }
  }
  return Object.freeze(list);
})();

export const TEST_BY_ID = Object.freeze(
  Object.fromEntries(TEST_REGISTRY.map((t) => [t.id, t]))
);

