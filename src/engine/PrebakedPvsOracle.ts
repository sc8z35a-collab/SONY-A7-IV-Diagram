export function buildPrebakedOcclusionMask(
  targetMode: 'integrated' | 'camera_body',
  partRecords: ReadonlyArray<{ part: { id: string }; slot: number }>,
  transparentPartSlots: ReadonlyArray<number>,
  capacity: number
): Uint16Array {
  const table = targetMode === 'integrated' ? PREBAKED_PVS_INTEGRATED : PREBAKED_PVS_CAMERA_BODY;
  const mask = new Uint16Array(capacity);
  const explicitSlot = new Uint8Array(capacity);
  for (let i = 0; i < partRecords.length; i++) {
    const rec = partRecords[i];
    const v = table[rec.part.id];
    if (v !== undefined) {
      mask[rec.slot] = v;
      explicitSlot[rec.slot] = 1;
    } else {
      mask[rec.slot] = 0xffff;
    }
  }
  for (let i = 0; i < transparentPartSlots.length; i++) {
    const s = transparentPartSlots[i];
    if (s >= 0 && s < capacity && explicitSlot[s] === 0) {
      mask[s] = 0xffff;
    }
  }
  return mask;
}
